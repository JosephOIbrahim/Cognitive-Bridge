# Gap 2 — Multi-level orphan cascade (4 levels deep)
# ═══════════════════════════════════════════════════════════════════════════


class TestMultiLevelOrphanCascade:
    """Gap 2: falsify_assertion only ORPHANs direct dependents (one level).

    The DAG:
        A @ /level/one (LOCAL, falsifiable)
        B @ /level/two  depends_on: [/level/one]
        C @ /level/three depends_on: [/level/two]
        D @ /level/four  depends_on: [/level/three]

    Falsifying A marks A FALSIFIED and B ORPHANED (direct), but C and D
    are not directly affected by the falsification call — they depend on
    /level/two and /level/three respectively, not on /level/one.
    """

    def _build_chain_stage(self) -> tuple[CompositionStage, str, str, str, str]:
        """Build a 4-level dependency chain and return (stage, id_a, id_b, id_c, id_d)."""
        stage = CompositionStage(project_id="orphan_chain", project_name="Orphan Chain")

        ast_a = Assertion(
            topic_path="/level/one",
            content="Foundation claim at level one",
            arc=CompositionArc.LOCAL,
            author=AssertionAuthor.AI,
            falsifiable_if="If level-one assumption is disproven by experiment",
        )
        stage.assertions[ast_a.id] = ast_a

        ast_b = Assertion(
            topic_path="/level/two",
            content="Derived claim at level two",
            arc=CompositionArc.INHERITS,
            author=AssertionAuthor.AI,
            depends_on_paths=["/level/one"],
        )
        stage.assertions[ast_b.id] = ast_b

        ast_c = Assertion(
            topic_path="/level/three",
            content="Derived claim at level three",
            arc=CompositionArc.INHERITS,
            author=AssertionAuthor.AI,
            depends_on_paths=["/level/two"],
        )
        stage.assertions[ast_c.id] = ast_c

        ast_d = Assertion(
            topic_path="/level/four",
            content="Derived claim at level four",
            arc=CompositionArc.SPECIALIZES,
            author=AssertionAuthor.AI,
            depends_on_paths=["/level/three"],
        )
        stage.assertions[ast_d.id] = ast_d

        return stage, ast_a.id, ast_b.id, ast_c.id, ast_d.id

    def test_falsified_assertion_is_marked_falsified(self) -> None:
        """After falsify_assertion(A), A's assumption_status is FALSIFIED."""
        stage, id_a, id_b, id_c, id_d = self._build_chain_stage()
        falsify_assertion(stage, id_a, "Experiment showed level-one is wrong")
        assert stage.assertions[id_a].assumption_status == AssumptionStatus.FALSIFIED

    def test_direct_dependent_is_orphaned(self) -> None:
        """B, which directly depends on /level/one, becomes ORPHANED."""
        stage, id_a, id_b, id_c, id_d = self._build_chain_stage()
        falsify_assertion(stage, id_a, "Experiment showed level-one is wrong")
        assert stage.assertions[id_b].assumption_status == AssumptionStatus.ORPHANED

    def test_indirect_dependent_stays_live(self) -> None:
        """C depends on /level/two (not /level/one directly) — stays LIVE after falsifying A."""
        stage, id_a, id_b, id_c, id_d = self._build_chain_stage()
        falsify_assertion(stage, id_a, "Experiment showed level-one is wrong")
        # C's dependency path is /level/two, not /level/one. check_falsification
        # only orphans direct dependents of the falsified path.
        assert stage.assertions[id_c].assumption_status == AssumptionStatus.LIVE

    def test_level_four_stays_live(self) -> None:
        """D depends only on /level/three — stays LIVE after falsifying A."""
        stage, id_a, id_b, id_c, id_d = self._build_chain_stage()
        falsify_assertion(stage, id_a, "Experiment showed level-one is wrong")
        assert stage.assertions[id_d].assumption_status == AssumptionStatus.LIVE

    def test_falsified_assertion_is_deactivated(self) -> None:
        """Falsified assertion has active=False after falsify_assertion."""
        stage, id_a, id_b, id_c, id_d = self._build_chain_stage()
        falsify_assertion(stage, id_a, "Experiment showed level-one is wrong")
        assert stage.assertions[id_a].active is False

    def test_orphaned_dependent_stays_active(self) -> None:
        """B is ORPHANED but still active (not retracted — different lifecycle)."""
        stage, id_a, id_b, id_c, id_d = self._build_chain_stage()
        falsify_assertion(stage, id_a, "Experiment showed level-one is wrong")
        # ORPHANED changes assumption_status but does not set active=False
        assert stage.assertions[id_b].active is True

    def test_retract_b_then_c_becomes_orphaned(self) -> None:
        """If B is then retracted, C (depending on /level/two) becomes ORPHANED."""
        stage, id_a, id_b, id_c, id_d = self._build_chain_stage()
        falsify_assertion(stage, id_a, "Experiment showed level-one is wrong")
        # B is now orphaned; retract it to propagate to C
        retract_assertion(stage, id_b)
        assert stage.assertions[id_c].assumption_status == AssumptionStatus.ORPHANED

    def test_events_recorded_for_falsification(self) -> None:
        """ASSERTION_FALSIFIED and ASSERTION_ORPHANED events are recorded."""
        stage, id_a, id_b, id_c, id_d = self._build_chain_stage()
        falsify_assertion(stage, id_a, "Experiment showed level-one is wrong")

        event_types = {e.event_type for e in stage.events}
        assert EventType.ASSERTION_FALSIFIED in event_types
        assert EventType.ASSERTION_ORPHANED in event_types

    def test_only_one_orphan_event_recorded_for_single_dependent(self) -> None:
        """Exactly one ASSERTION_ORPHANED event is recorded (only B is direct dependent)."""
        stage, id_a, id_b, id_c, id_d = self._build_chain_stage()
        falsify_assertion(stage, id_a, "Experiment showed level-one is wrong")

        orphan_events = [
            e for e in stage.events
            if e.event_type == EventType.ASSERTION_ORPHANED
        ]
        assert len(orphan_events) == 1
        assert orphan_events[0].target_id == id_b


