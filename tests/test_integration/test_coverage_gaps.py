# Gap 4 — Promote to same or weaker arc
# ═══════════════════════════════════════════════════════════════════════════


class TestPromoteToSameOrWeakerArc:
    """Gap 4: promote_assertion raises ValueError when new arc is not stronger."""

    def _make_inherits_stage(self) -> tuple[CompositionStage, str]:
        """Create a stage with a single INHERITS assertion and return (stage, id)."""
        stage = CompositionStage(project_id="promote_test", project_name="Promote Test")
        ast = Assertion(
            topic_path="/test/promote",
            content="Claim to be promoted",
            arc=CompositionArc.INHERITS,
            author=AssertionAuthor.AI,
        )
        stage.assertions[ast.id] = ast
        return stage, ast.id

    def test_promote_to_same_arc_raises(self) -> None:
        """Promoting INHERITS -> INHERITS (same arc) raises ValueError."""
        stage, ast_id = self._make_inherits_stage()
        with pytest.raises(ValueError, match="not stronger"):
            promote_assertion(stage, ast_id, CompositionArc.INHERITS)

    def test_promote_to_weaker_arc_raises(self) -> None:
        """Promoting INHERITS(20) -> REFERENCES(40) is a demotion — raises ValueError."""
        stage, ast_id = self._make_inherits_stage()
        with pytest.raises(ValueError, match="not stronger"):
            promote_assertion(stage, ast_id, CompositionArc.REFERENCES)

    def test_promote_to_weakest_arc_raises(self) -> None:
        """Promoting INHERITS(20) -> SPECIALIZES(60) raises ValueError."""
        stage, ast_id = self._make_inherits_stage()
        with pytest.raises(ValueError, match="not stronger"):
            promote_assertion(stage, ast_id, CompositionArc.SPECIALIZES)

    def test_promote_to_payloads_from_inherits_raises(self) -> None:
        """Promoting INHERITS(20) -> PAYLOADS(50) raises ValueError."""
        stage, ast_id = self._make_inherits_stage()
        with pytest.raises(ValueError, match="not stronger"):
            promote_assertion(stage, ast_id, CompositionArc.PAYLOADS)

    def test_promote_to_stronger_arc_succeeds(self) -> None:
        """Promoting INHERITS(20) -> LOCAL(10) succeeds (legitimate promotion)."""
        stage, ast_id = self._make_inherits_stage()
        # LOCAL requires falsifiable_if — we must supply it via the assertion update.
        # promote_assertion mutates the arc; we need a LOCAL-safe arc.
        # Use LOCAL which is stronger (10 < 20).
        # But LOCAL assertions need falsifiable_if — add it before promoting.
        stage.assertions[ast_id].falsifiable_if = "If the claim fails a test"
        result = promote_assertion(stage, ast_id, CompositionArc.LOCAL)
        assert result.assertion.arc == CompositionArc.LOCAL

    def test_promote_nonexistent_assertion_raises(self) -> None:
        """Promoting an ID that does not exist raises ValueError."""
        stage, _ = self._make_inherits_stage()
        with pytest.raises(ValueError, match="not found"):
            promote_assertion(stage, "ast_nonexistent", CompositionArc.LOCAL)

    def test_promote_retracted_assertion_raises(self) -> None:
        """Promoting a retracted (inactive) assertion raises ValueError."""
        stage, ast_id = self._make_inherits_stage()
        # Retract it first
        retract_assertion(stage, ast_id)
        with pytest.raises(ValueError, match="inactive"):
            promote_assertion(stage, ast_id, CompositionArc.LOCAL)

    def test_promote_error_message_names_arcs(self) -> None:
        """ValueError message names both old and new arc for diagnostics."""
        stage, ast_id = self._make_inherits_stage()
        with pytest.raises(ValueError) as exc_info:
            promote_assertion(stage, ast_id, CompositionArc.REFERENCES)
        msg = str(exc_info.value)
        # Message should reference the arc names or values
        assert "REFERENCES" in msg or "40" in msg
        assert "INHERITS" in msg or "20" in msg
