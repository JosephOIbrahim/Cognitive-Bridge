    async def test_arc_999_raises_value_error(self) -> None:
        """arc=999 is not a valid CompositionArc — returns ERROR string."""
        from cognitive_bridge.tools.assertion_tool import cb_manage_assertion

        ctx, stage, store = _make_ctx_with_stage("gap3_arc999")
        result = await cb_manage_assertion(
            action="assert",
            topic_path="/test/path",
            content="some claim",
            arc=999,
            ctx=ctx,
            project_id="gap3_arc999",
        )
        assert "ERROR" in result
        assert "Invalid arc" in result or "999" in result

