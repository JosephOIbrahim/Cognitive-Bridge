class _MockCtx:
    """Minimal context mock that satisfies ctx.lifespan_context access."""

    def __init__(self, store: SQLiteStore, stage: CompositionStage) -> None:
        self.lifespan_context = {
            "store": store,
            "active_stages": {stage.project_id: stage},
        }


def _make_ctx_with_stage(
    project_id: str = "gap_test",
) -> tuple["_MockCtx", CompositionStage, SQLiteStore]:
    """Build a wired (ctx, stage, store) triple for tool-level tests."""
    from cognitive_bridge.server import save_stage_to_db

    store = SQLiteStore(":memory:")
    stage = CompositionStage(project_id=project_id, project_name="Gap Test")
    save_stage_to_db(store, stage)
    ctx = _MockCtx(store=store, stage=stage)
    return ctx, stage, store


