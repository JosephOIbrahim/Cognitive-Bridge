def _build_full_stage() -> CompositionStage:
    """Build a maximally populated stage covering every model type."""
    stage = CompositionStage(
        project_id="rt_full_001",
        project_name="Full Round-Trip",
    )
    stage.exchange_count = 42

    # --- Custom CognitiveParameters (not defaults) ---
    stage.parameters.conflict_sensitivity = 0.91
    stage.parameters.semantic_threshold = 0.88
    stage.parameters.cross_path_detection = True
    stage.parameters.exploration_budget = 7
    stage.parameters.red_team_threshold = 15
    stage.parameters.cascade_auto_challenge = False
    stage.parameters.payload_surfacing = False
    stage.parameters.ai_default_arc = CompositionArc.REFERENCES

    # --- Assertions at different paths with various arcs & dependencies ---
    # A: LOCAL at /db (root for DAG)
    ast_a = Assertion(
        topic_path="/db",
        content="PostgreSQL is the primary datastore",
        arc=CompositionArc.LOCAL,
        author=AssertionAuthor.AI,
        falsifiable_if="If another DB engine is chosen by the team",
    )
    stage.assertions[ast_a.id] = ast_a

    # B: INHERITS at /db/orm, depends on /db
    ast_b = Assertion(
        topic_path="/db/orm",
        content="Prisma is the ORM layer",
        arc=CompositionArc.INHERITS,
        author=AssertionAuthor.AI,
        depends_on_paths=["/db"],
    )
    stage.assertions[ast_b.id] = ast_b

    # C: REFERENCES at /db/hosting
    ast_c = Assertion(
        topic_path="/db/hosting",
        content="Database is hosted on AWS RDS",
        arc=CompositionArc.REFERENCES,
        author=AssertionAuthor.USER,
    )
    stage.assertions[ast_c.id] = ast_c

    # D: SPECIALIZES at /api/schema, depends on /db/orm
    ast_d = Assertion(
        topic_path="/api/schema",
        content="API schema is auto-generated by Prisma",
        arc=CompositionArc.SPECIALIZES,
        author=AssertionAuthor.AI,
        depends_on_paths=["/db/orm"],
    )
    stage.assertions[ast_d.id] = ast_d

    # E: PAYLOADS at /compliance
    ast_e = Assertion(
        topic_path="/compliance",
        content="GDPR compliance audit pending",
        arc=CompositionArc.PAYLOADS,
        author=AssertionAuthor.SYSTEM,
        depends_on_paths=["/db"],
    )
    stage.assertions[ast_e.id] = ast_e

    # --- Conflicts ---
    # Active conflict between ast_a and a hypothetical MongoDB claim
    cfl_active = Conflict(
        assertion_a_id=ast_a.id,
        assertion_b_id=ast_c.id,
        topic_path="/db",
        detection_layer=ConflictDetectionLayer.STRUCTURAL,
        steelman_of_opponent="MongoDB offers flexible schema — suits evolving requirements",
    )
    stage.conflicts[cfl_active.id] = cfl_active

    # Resolved conflict
    cfl_resolved = Conflict(
        assertion_a_id=ast_b.id,
        assertion_b_id=ast_d.id,
        topic_path="/db/orm",
        detection_layer=ConflictDetectionLayer.CASCADING,
        status=ConflictStatus.RESOLVED_SYNTHESIZED,
        resolution_chosen=ResolutionPath.SYNTHESIZE,
        resolution_note="Both claims are compatible; schema generation follows ORM.",
    )
    stage.conflicts[cfl_resolved.id] = cfl_resolved

    # --- VariantSet with 2 variants ---
    vs = VariantSet(
        name="Database Options",
        topic_path="/db",
        variants=[
            Variant(
                name="PostgreSQL",
                content="Relational; strong ACID guarantees",
                evidence_for=["joins", "ACID"],
            ),
            Variant(
                name="MongoDB",
                content="Document store; flexible schema",
                evidence_for=["flexible schema"],
                evidence_against=["no joins"],
            ),
        ],
        source_conflict_id=cfl_active.id,
    )
    stage.variant_sets[vs.id] = vs

    # --- Decisions ---
    dec_a = Decision(
        topic_path="/db",
        decision="Use PostgreSQL for the primary datastore",
        rationale="Team has SQL expertise and schema is well-defined",
        alternatives_rejected=[
            "MongoDB — rejected because no native join support",
            "MySQL — rejected because Prisma ORM support is weaker",
        ],
        second_order_effects=[
            "All queries must use SQL dialect",
            "Schema migrations required via Prisma migrate",
        ],
    )
    stage.decisions.append(dec_a)

    dec_b = Decision(
        topic_path="/api/schema",
        decision="Auto-generate API schema from Prisma models",
        rationale="Single source of truth reduces drift between DB and API",
        alternatives_rejected=["Hand-crafted OpenAPI — rejected because of maintenance burden"],
        second_order_effects=["Schema changes must go through Prisma first"],
    )
    stage.decisions.append(dec_b)

    # --- Events ---
    for evt_type in [
        EventType.ASSERTION_CREATED,
        EventType.ASSERTION_PROMOTED,
        EventType.CONFLICT_DETECTED,
        EventType.CONFLICT_RESOLVED,
        EventType.ASSERTION_CHALLENGED,
        EventType.ASSERTION_FALSIFIED,
        EventType.ASSERTION_ORPHANED,
        EventType.VARIANT_SET_CREATED,
        EventType.DECISION_RECORDED,
        EventType.PARAMETERS_TUNED,
    ]:
        stage.record_event(
            evt_type,
            AssertionAuthor.SYSTEM,
            "target_001",
            {"test_event": evt_type.value},
        )

    return stage


